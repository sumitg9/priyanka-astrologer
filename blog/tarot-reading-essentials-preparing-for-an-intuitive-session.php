        <h2 id="classic-spreads">5. Classic Tarot Spreads for Life Decisions</h2>
        <p>
          Depending on the complexity of your situation, different geometric card layouts (spreads) are employed:
        </p>
        <ol>
          <li>
            <strong>The Three-Card Clarity Spread:</strong>
            Clean and focused. Can be configured as <em>Past &ndash; Present &ndash; Future</em>, <em>Situation &ndash;
              Underlying Obstacle &ndash; Highest Outcome</em>, or <em>Mind &ndash; Body &ndash; Spirit</em>.
          </li>
          <li>
            <strong>The Celtic Cross Spread (10 Cards):</strong>
            The legendary classical diagnostic layout. Dissects your core heart issue, immediate hurdles, conscious
            hopes, subconscious roots, external environmental influences, and probable trajectories.
          </li>
          <li>
            <strong>The Relationship Synergy Spread (7 Cards):</strong>
            Maps both partners' emotional mindsets, mutual expectations, unspoken fears, and shared healing potential
            (<a href="../kundali-matching.php">pairs perfectly with Kundali Matching</a>).
          </li>
          <li>
            <strong>The Two-Path Crossroads Spread:</strong>
            Ideal when choosing between two job offers, investments, or residential locations, comparing the energetic
            trajectory of Path A vs. Path B.
          </li>
        </ol>

        <h2 id="how-to-prepare">6. Preparing Your Mind &amp; Space Before a Consultation</h2>
        <p>
          To derive maximum benefit from your session with Priyanka Dey, simple mindful preparation creates a receptive
          energetic container:
        </p>
        <ul>
          <li><strong>Write Down Your Topics in Advance:</strong> Note down 2 to 4 core themes you wish to explore
            (e.g., career pivot, relationship tension, personal fulfillment).</li>
          <li><strong>Find a Quiet, Private Space:</strong> Ensure you are in a quiet room free from distractions,
            interruptions, or household noise, especially for online video sessions.</li>
          <li><strong>Take Three Deep Breaths:</strong> Before beginning, take a few conscious deep breaths to
            transition out of frantic work mode and into calm, intuitive presence.</li>
          <li><strong>Keep an Open Mind:</strong> Be prepared to hear constructive truths. The cards often point toward
            internal changes in perception rather than external fixes.</li>
        </ul>

